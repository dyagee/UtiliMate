  void _generateName() {
    setState(() {
      final List<String> maleNames =
          _firstNames[_selectedLocale]![GenderOption.male]!;
      final List<String> femaleNames =
          _firstNames[_selectedLocale]![GenderOption.female]!;
      final List<String> lastNames = _surnames[_selectedLocale]!;

      String firstName = '';
      String lastName = lastNames[_random.nextInt(lastNames.length)];

      if (_selectedGender == GenderOption.male) {
        firstName = maleNames[_random.nextInt(maleNames.length)];
      } else if (_selectedGender == GenderOption.female) {
        firstName = femaleNames[_random.nextInt(femaleNames.length)];
      } else {
        // GenderOption.any: randomly pick from combined male and female names
        List<String> combinedFirstNames = [...maleNames, ...femaleNames];
        firstName =
            combinedFirstNames[_random.nextInt(combinedFirstNames.length)];
      }

      _generatedName = "$firstName $lastName";
    });
  }

